import { Router } from "express";
import { nanoid } from "nanoid";
import * as db from "./db";
import { hashApiToken } from "./utils/apiToken";

const router = Router();

/**
 * Playwright Reporter API
 * POST /api/playwright/report
 * 
 * Accepts test results from Playwright custom reporter
 * and creates/updates test runs and executions
 */
router.post("/report", async (req, res) => {
  try {
    // Authenticate with a project API token: "Authorization: Bearer qlt_..." (created in Settings)
    const header = req.headers.authorization ?? "";
    const presented = header.startsWith("Bearer ") ? header.slice(7).trim() : "";
    const token = presented ? await db.getApiTokenByHash(hashApiToken(presented)) : null;
    if (!token) {
      return res.status(401).json({
        success: false,
        error: "Missing or invalid API token. Send 'Authorization: Bearer <token>'; create a token in the project's Settings > Playwright Reporter tab.",
      });
    }

    // The token decides the project; a projectId in the body is optional but must match
    const projectId = token.projectId;
    if (req.body?.projectId && req.body.projectId !== projectId) {
      return res.status(403).json({ success: false, error: "This API token belongs to a different project" });
    }
    if (!(await db.getProjectById(projectId))) {
      return res.status(403).json({ success: false, error: "The project for this API token no longer exists" });
    }

    const { runName, results } = req.body ?? {};
    if (!runName || !Array.isArray(results)) {
      return res.status(400).json({
        success: false,
        error: "Missing required fields: runName, results",
      });
    }
    await db.touchApiToken(token.id);

    // Create a new test run
    const runId = nanoid();
    const run = {
      id: runId,
      projectId,
      runNumber: 0, // Will be auto-generated by createTestRun
      name: runName,
      description: `Automated test run from Playwright - ${new Date().toISOString()}`,
      createdBy: "playwright-reporter",
      completedAt: new Date(),
    };

    await db.createTestRun(run);

    // The UI shows a case's type through the project's "Type" custom field, not the testType column
    const customFields = await db.getCustomFieldsByProject(projectId);
    const typeField = customFields.find(
      f => f.name.toLowerCase() === "type" && (f.options ?? "").split(",").map(o => o.trim()).includes("automated")
    );

    // Process each test result
    const executionIds: string[] = [];
    for (const result of results) {
      const { testCaseTitle, status, duration, errorMessage } = result;

      // Try to find existing test case by TC-# identifier or title
      const existingTestCases = await db.getTestCasesByProject(projectId);
      let testCase;

      // Check if test name contains TC-# identifier
      const tcMatch = testCaseTitle.match(/TC-(\d+)/);
      if (tcMatch) {
        const testCaseNumber = parseInt(tcMatch[1], 10);
        testCase = existingTestCases.find(tc => tc.testCaseNumber === testCaseNumber);
      }

      // If not found by TC-#, try to find by exact title match
      if (!testCase) {
        testCase = existingTestCases.find(tc => tc.title === testCaseTitle);
      }

      if (!testCase) {
        // Create new test case
        const testCaseId = nanoid();
        const testCaseNumber = await db.getNextTestCaseNumber(projectId);
        const newTestCase = {
          id: testCaseId,
          projectId,
          testCaseNumber,
          folderId: null,
          title: testCaseTitle,
          description: "Auto-created from Playwright test",
          preconditions: null,
          testType: "automated" as const,
          priority: "medium" as const,
          createdBy: "playwright-reporter",
        };
        await db.createTestCase(newTestCase);
        testCase = await db.getTestCaseById(testCaseId);
      }

      if (!testCase) {
        console.error("Failed to create or find test case");
        continue;
      }

      // Mark the case as automated unless its Type was already set (never overwrite e.g. "manual")
      if (typeField) {
        const values = await db.getCustomFieldValuesByTestCase(testCase.id);
        if (!values.some(v => v.customFieldId === typeField.id)) {
          await db.createCustomFieldValue({
            id: nanoid(),
            testCaseId: testCase.id,
            customFieldId: typeField.id,
            value: "automated",
          });
        }
      }

      // Create test execution
      const executionId = nanoid();
      await db.createTestExecution({
        id: executionId,
        testRunId: runId,
        testCaseId: testCase.id,
        status: status || "not_run",
        executedBy: "playwright-reporter",
        executedAt: new Date(),
        duration: duration || null,
        comment: null,
        errorMessage: errorMessage || null,
      });

      executionIds.push(executionId);
    }

    return res.json({
      success: true,
      runId,
      executionCount: executionIds.length,
    });
  } catch (error) {
    console.error("[Playwright Reporter] Error processing results:", error);
    return res.status(500).json({
      success: false,
      error: "Internal server error",
    });
  }
});

export default router;

